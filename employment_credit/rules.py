def get_all_selectable_doc_labels(tax_year: int = DEFAULT_TAX_YEAR) -> dict[str, str]:
    """
    드롭다운에서 선택 가능한 전체 서류 라벨 딕셔너리.
    기본 7종 외에 2021~2028년 모든 연도의 원천징수부와 근로계약서·4대보험 명부 등 추가 서류를 모두 지원합니다.
    """
    base = {k: lbl for k, lbl, _, _ in get_doc_types(tax_year)}
    for y in sorted(WHT_YEAR_RANGE, reverse=True):
        wk = f"wht_{y}"
        if wk not in base:
            base[wk] = f"{y}년 소득자별 근로소득원천징수부 (추가 과거/비교연도)"
    base["labor_contract"] = "근로계약서 · 4대보험 명부 · 기타 보충서류"
    return base


