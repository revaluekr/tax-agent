def build_amendment_summary_markdown(
    law_status: dict[str, Any] | None = None,
    target_law: str | None = None,
    tax_year: int = DEFAULT_TAX_YEAR,
) -> str:
    """
    상세보기 모달의 맨 앞 [개정요약] 탭(target_law=None) 또는 개별 법령 탭 상단(target_law 지정 시)에
    표시할 개정 사항 요약 마크다운을 생성합니다.
    - 검증된 상수 요약문(AMENDMENT_SUMMARIES)은 기준 해시 미설정 상태에서도 항상 표시하며,
      해당 법령에서 기준 버전 이후 미반영 추가 개정(is_unapplied=True)이 감지된 경우에만
      '요약 재검토 필요(원문 변경 감지)' 안내 배지를 함께 표시합니다.
    """
    laws_map = (law_status or {}).get("laws") or {}
    items = [
        it for it in AMENDMENT_SUMMARIES
        if target_law is None or it.get("개정법령") == target_law
    ]
    if not items:
        return ""

    md_lines: list[str] = []
    if target_law is None:
        md_lines.extend([
            "### 1. 통합고용세액공제 핵심 개정 사항 한눈에 보기 (종전 vs 개정 비교표)",
            "",
            "| 개정 법령 및 대상 조·항·부칙 | 공포번호 (시행일) | 종전 규정 | 개정 규정 | 적용 시기 및 대상 |",
            "| :--- | :---: | :--- | :--- | :--- |",
        ])
        for it in items:
            short_art = str(it.get("대상조항") or "").replace(str(it.get("개정법령") or ""), "").strip()
            md_lines.append(
                f"| **[{it['개정법령']}]**<br>{short_art} | **{it['공포번호']}**<br>({it['시행일']} 시행) | {it['종전_규정']} | **{it['개정_규정']}** | {it['적용시기_대상']} |"
            )
        md_lines.extend([
            "",
            "### 2. 법령·조항별 상세 개정 내용 요약 (원문 문언 및 부칙 적용례 근거)",
            "",
        ])
    else:
        md_lines.extend([
            f"### 1. {target_law} 개정 사항 요약",
            "",
        ])

    for idx, it in enumerate(items, start=1):
        law_nm = str(it.get("개정법령") or "")
        l_info = laws_map.get(law_nm) or {}
        is_unapplied = bool(l_info.get("is_unapplied"))
        md_lines.append(
            f"#### ({idx}) [{it['대상조항']}] ({it['공포번호']}, {it['공포일']} 공포 · {it['시행일']} 시행)"
        )
        md_lines.append("")
        if is_unapplied:
            md_lines.append(
                "- **[요약 재검토 필요(원문 변경 감지)]** 법제처 현행 원문이 기준 버전 이후 변경되었습니다. 아래 기준 요약과 함께 현행 원문 대비표를 확인하시기 바랍니다."
            )
        for sent in it.get("요약문") or []:
            md_lines.append(f"- {sent}")
        md_lines.append("")
        badge_txt = str(it.get("앱_판정_배지") or "")
        meta_txt = f"작성일: {it.get('작성일', '-')} · 검토: {it.get('검토자', '-')}"
        md_lines.append(
            f"<div style='margin:4px 0 14px 0;padding:8px 12px;background:#f1f5f9;border:1px solid #cbd5e1;"
            f"border-left:4px solid #475569;border-radius:6px;font-size:0.92rem;color:#334155;font-weight:700;'>"
            f"프로그램 적용 상태 ({tax_year}년 귀속 선택 기준): {badge_txt} "
            f"<span style='font-weight:500;color:#64748b;font-size:0.84rem;'>({meta_txt})</span>"
            f"</div>"
        )
        md_lines.append("")

    if target_law is None:
        md_lines.append(
            "<div style='margin:2px 0 10px 0;padding:8px 12px;background:#eff6ff;border:1px solid #bfdbfe;"
            "border-radius:6px;font-size:0.92rem;color:#1e3a8a;font-weight:700;'>"
            "상단 가로 탭에서 [조세특례제한법], [조세특례제한법 시행령], [시행규칙·서식], [농어촌특별세법], [예규·안내문 원문] 탭을 클릭하면 해당 법령의 조문·부칙 전문 칸으로 바로 이동합니다."
            "</div>"
        )
        md_lines.append("")

    return "\n".join(md_lines)


def format_admin_rulings_for_prompt() -> str:
    """
    AI 심층 세무진단 프롬프트 및 화면 노출용 행정해석 원문 반환.
    - 원칙: AI 프롬프트와 화면에는 반드시 '원문' 필드(및 '출처' 표기)만 넣으며, '앱_요약'은 섞지 않는다.
    """
    blocks: list[str] = ["[국세청 '26.3월 안내문 및 법정서식 원문]"]
    for item in ADMIN_RULINGS_AND_NOTICES.values():
        src = item.get("출처") or {}
        if isinstance(src, dict):
            src_label = f"{src.get('문서명', '')} ({src.get('발행기관', '')}, {src.get('발행연월', '')})"
        else:
            src_label = str(src)
        blocks.append(f"[출처: {src_label}]\n{item.get('원문', '')}")
    return "\n\n".join(blocks)




